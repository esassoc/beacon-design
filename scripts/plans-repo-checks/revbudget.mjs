import { open, BASE, HIDE } from './lib.mjs';
const { OUT } = await import('./lib.mjs');
const { browser, page, planID } = await open({ scale: 2 });
let pass = 0, fail = 0;
const check = (n, ok, x = '') => { ok ? pass++ : fail++; console.log(`${ok ? 'PASS' : 'FAIL'} ${n}${x ? ' :: ' + x : ''}`); };
await page.goto(`${BASE}/prototypes/plans-repo/plan/?id=${planID}&about=closed&view=budget`);
await page.addStyleTag({ content: HIDE });
await page.waitForSelector('[data-pbs-grid] .ag-row[row-id]'); await page.waitForTimeout(1000);
await page.click('[data-prp-edit] button'); await page.waitForTimeout(1500);
const c = page.locator('[data-pbs-grid] .ag-center-cols-container .ag-cell.bcn-pbs__editable').first();
const before = Number((await c.textContent()).replace(/[^0-9]/g, '')) || 0;
const net = '+$' + (250000 - before).toLocaleString('en-US');
await c.click(); await page.keyboard.type('250k'); await page.keyboard.press('Enter'); await page.waitForTimeout(1500);
await page.click('[data-prp-review] button'); await page.waitForTimeout(1800);
const counts = (await page.locator('[data-prvd-counts]').textContent()).replace(/\s+/g, ' ').trim();
check('counts include budget', /1 Budget Change/.test(counts), counts);
check('budget section', (await page.locator('[data-prvd-rows] .bcn-prvd__section', { hasText: 'Budget' }).count()) === 1);
const money = (await page.locator('[data-prvd-rows] .bcn-prvd__cell--to .bcn-prvd__money').allTextContents()).join(' | ');
check('budget row shows new figure and net', /\$250,000/.test(money) && money.includes(net), money + ' expected ' + net);
check('publish enabled for budget-only draft', !(await page.locator('[data-prvd-publish] button').isDisabled()));
await page.screenshot({ path: OUT + 'rv-budget-review.png' });
await page.locator('[data-prvd-publish] button').click(); await page.waitForTimeout(2500);
await page.click('[data-prp-history-link]'); await page.waitForTimeout(1800);
const hist = (await page.locator('[data-prvd-counts]').textContent()).replace(/\s+/g, ' ').trim();
check('history shows the budget change', /Budget Change/.test(hist), hist);
await page.screenshot({ path: OUT + 'rv-budget-history.png' });
console.log(`\n${pass} PASS, ${fail} FAIL`);
await browser.close();
